// Regenerate the bundled attract-mode demo replay for the CURRENT game version.
// Usage: node tools/make-demo.mjs          write games/starfall/demo-replay.js
//        node tools/make-demo.mjs --check  exit 1 if the bundled demo is for another version (writes nothing)
// Run it whenever GAME_VERSION changes. If the demo is stale, attract mode falls back to the high-score table only.
// The demo is a fixed-seed run played by a simple bot (dodge falling shots, else chase the nearest enemy and fire),
// 1150 frames (about 19 s) of stage 1. Same code and seed always give the same replay string.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createSim, GAME_ID, GAME_VERSION } from '../games/starfall/sim.js';
import { packWord } from '../engine/input-word.js';
import { createRecorder, decode } from '../engine/replay.js';

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../games/starfall/demo-replay.js');
export const DEMO_SEED = 20261028, DEMO_FRAMES = 1150;

function botMove(sim) {
  const p = sim.player;
  let threat = 0, best = 1e9;
  for (const b of sim.eb) {
    if (!b.on || b.vy <= 0) continue;
    const dy = p.y - b.y; if (dy < -6 || dy > 70) continue;
    const t = Math.max(0, dy / b.vy), dx = b.x + b.vx * t - p.x;
    if (Math.abs(dx) < 14 && dy < best) { best = dy; threat = dx; }
  }
  for (const e of sim.enemies) {
    if (e.st !== 'dive' && e.st !== 'spark') continue;
    const dy = p.y - e.y; if (dy < -8 || dy > 60) continue;
    const dx = e.x - p.x; if (Math.abs(dx) < 16 && dy < best) { best = dy; threat = dx; }
  }
  if (best < 1e9) { const away = threat > 0 ? -1 : 1; return p.x < 30 ? 1 : p.x > 370 ? -1 : away; }
  let tx = 200, bd = 1e9;
  for (const e of sim.enemies) if (e.st !== 'wait') { const d = Math.abs(e.x - p.x); if (d < bd) { bd = d; tx = e.x; } }
  const d = tx - p.x;
  return Math.abs(d) < 3 ? 0 : Math.max(-1, Math.min(1, d / 20));
}

export function makeDemo() {
  const sim = createSim({ seed: DEMO_SEED, mode: 'arcade' }), rec = createRecorder(1024);
  for (let f = 0; f < DEMO_FRAMES && !sim.done; f++) {
    const w = packWord(botMove(sim), true, f % 9 === 0, sim.meter >= 10, false, 0);
    sim.step(w); rec.push(w); sim.clearEvents();
  }
  return { replay: rec.encode({ game: GAME_ID, version: GAME_VERSION, seed: DEMO_SEED, mode: 'arcade' }), score: sim.score, frames: sim.frame, hash: sim.stateHash() };
}

if (process.argv[1] && process.argv[1].endsWith('make-demo.mjs')) {
  if (process.argv.includes('--check')) {
    let cur = null;
    try { cur = decode((await import('../games/starfall/demo-replay.js')).DEMO_REPLAY); } catch (e) { /* missing or unreadable */ }
    if (cur && cur.version === GAME_VERSION && cur.game === GAME_ID) { console.log(`demo replay is current (${GAME_ID} ${GAME_VERSION})`); process.exit(0); }
    console.error(`demo replay is stale or missing (game version ${GAME_VERSION}); run: node tools/make-demo.mjs`); process.exit(1);
  }
  const d = makeDemo();
  fs.writeFileSync(OUT, `// Bundled attract-mode demo replay for ${GAME_ID} ${GAME_VERSION}. GENERATED by tools/make-demo.mjs: do not edit by hand.\n` +
    `// Regenerate whenever GAME_VERSION changes. A demo for another version is ignored by attract mode.\n` +
    `export const DEMO_REPLAY = '${d.replay}';\n`);
  console.log(JSON.stringify({ wrote: path.relative(process.cwd(), OUT), version: GAME_VERSION, frames: d.frames, score: d.score, hash: d.hash }));
}
