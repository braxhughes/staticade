export function textW(str, sc) { return str.length * 6 * sc - sc; }

// text(str, x, y, col, sc, align 'c'|'r'|'l', alpha, wave). clock.F drives the wave animation.
export function createText(dot, clock) {
  return function text(str, x, y, col, sc, align, a, wave) {
    sc = sc || 1; a = a == null ? 1 : a;
    const w = textW(str, sc);
    let x0 = align === 'c' ? x - w / 2 : align === 'r' ? x - w : x;
    for (let i = 0; i < str.length; i++) {
      const g = FONT[str[i]];
      if (g) {
        const wy = wave ? Math.sin(clock.F * 0.12 + i * 0.6) * wave : 0;
        for (let r = 0; r < 7; r++) {
          const row = g[r];
          if (!row) continue;
          for (let b = 0; b < 5; b++) if ((row >> (4 - b)) & 1) dot(x0 + b * sc, y + r * sc + wy, sc * 0.95, col[0], col[1], col[2], a);
        }
      }
      x0 += 6 * sc;
    }
  };
}
